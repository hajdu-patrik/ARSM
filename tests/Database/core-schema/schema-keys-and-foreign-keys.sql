-- AutoService DB - primary keys, identity columns and foreign keys with their delete rules.
-- Assertion idiom: a violation makes the closing cast fail; delete rules: c cascade, n set null.

-- 1. Every table has exactly the modelled primary key (ordered column list).
SELECT 'primary_keys' AS check_name,
       CASE WHEN COUNT(*) = 0 THEN 'ok'
            ELSE concat('FAIL primary_keys: ', COUNT(*), ' mismatch(es), e.g. ', MIN(v.detail))::int::text END AS check_result
FROM (
    SELECT COALESCE(e.tbl, a.tbl) || ' expected (' || COALESCE(e.cols, 'none') || ') got (' || COALESCE(a.cols, 'none') || ')' AS detail
    FROM (VALUES
        ('AspNetRoleClaims', 'Id'), ('AspNetRoles', 'Id'), ('AspNetUserClaims', 'Id'),
        ('AspNetUserLogins', 'LoginProvider,ProviderKey'), ('AspNetUserRoles', 'UserId,RoleId'),
        ('AspNetUsers', 'Id'), ('AspNetUserTokens', 'UserId,LoginProvider,Name'),
        ('__EFMigrationsHistory', 'MigrationId'), ('appointmentmechanics', 'AppointmentId,MechanicId'),
        ('appointments', 'Id'), ('companyprofiles', 'Id'), ('labortypes', 'Id'), ('parts', 'Id'),
        ('people', 'Id'), ('quotelines', 'Id'), ('quotes', 'Id'), ('refreshtokens', 'Id'),
        ('revokedjwttokens', 'Id'), ('vehicles', 'Id')
    ) AS e (tbl, cols)
    FULL JOIN (
        SELECT t.relname::text AS tbl,
               string_agg(a.attname::text, ',' ORDER BY k.ord) AS cols
        FROM pg_constraint c
        JOIN pg_class t ON t.oid = c.conrelid
        JOIN pg_namespace n ON n.oid = t.relnamespace AND n.nspname = 'public'
        CROSS JOIN LATERAL unnest(c.conkey) WITH ORDINALITY AS k (attnum, ord)
        JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.attnum
        WHERE c.contype = 'p'
        GROUP BY t.relname, c.oid
    ) a ON a.tbl = e.tbl
    WHERE e.tbl IS NULL
       OR a.tbl IS NULL
       OR e.cols <> a.cols
) v;


-- 2. Id columns are GENERATED BY DEFAULT AS IDENTITY, except companyprofiles.Id, which is pinned to 1 by a CHECK.
SELECT 'identity_columns' AS check_name,
       CASE WHEN COUNT(*) = 0 THEN 'ok'
            ELSE concat('FAIL identity_columns: ', COUNT(*), ' mismatch(es), e.g. ', MIN(v.detail))::int::text END AS check_result
FROM (
    SELECT e.tbl || '.Id identity is ' || COALESCE(c.is_identity::text, 'missing') || '/' || COALESCE(c.identity_generation::text, 'none') AS detail
    FROM (VALUES
        ('AspNetRoleClaims', TRUE), ('AspNetUserClaims', TRUE), ('appointments', TRUE), ('labortypes', TRUE),
        ('parts', TRUE), ('people', TRUE), ('quotelines', TRUE), ('quotes', TRUE),
        ('refreshtokens', TRUE), ('revokedjwttokens', TRUE), ('vehicles', TRUE), ('companyprofiles', FALSE)
    ) AS e (tbl, is_identity)
    LEFT JOIN information_schema.columns c
           ON c.table_schema = 'public'
          AND c.table_name = e.tbl
          AND c.column_name = 'Id'
    WHERE c.column_name IS NULL
       OR (e.is_identity AND (c.is_identity <> 'YES' OR c.identity_generation IS DISTINCT FROM 'BY DEFAULT'))
       OR (NOT e.is_identity AND c.is_identity <> 'NO')
) v;


-- 3. The foreign keys are exactly the modelled ones, with their delete rule; people.IdentityUserId has none.
--    quotes.AppointmentId cascades (QuoteAppointmentCascade); quote creators and line catalog links set null.
SELECT 'foreign_keys' AS check_name,
       CASE WHEN COUNT(*) = 0 THEN 'ok'
            ELSE concat('FAIL foreign_keys: ', COUNT(*), ' mismatch(es), e.g. ', MIN(v.detail))::int::text END AS check_result
FROM (
    SELECT COALESCE(e.tbl, a.tbl) || '.' || COALESCE(e.col, a.col)
           || ' expected ' || COALESCE(e.ref_tbl || '.' || e.ref_col || ' ' || e.rule, 'none')
           || ' got ' || COALESCE(a.ref_tbl || '.' || a.ref_col || ' ' || a.rule, 'none') AS detail
    FROM (VALUES
        ('AspNetRoleClaims', 'RoleId', 'AspNetRoles', 'Id', 'c'),
        ('AspNetUserClaims', 'UserId', 'AspNetUsers', 'Id', 'c'),
        ('AspNetUserLogins', 'UserId', 'AspNetUsers', 'Id', 'c'),
        ('AspNetUserRoles', 'RoleId', 'AspNetRoles', 'Id', 'c'),
        ('AspNetUserRoles', 'UserId', 'AspNetUsers', 'Id', 'c'),
        ('AspNetUserTokens', 'UserId', 'AspNetUsers', 'Id', 'c'),
        ('appointmentmechanics', 'AppointmentId', 'appointments', 'Id', 'c'),
        ('appointmentmechanics', 'MechanicId', 'people', 'Id', 'c'),
        ('appointments', 'VehicleId', 'vehicles', 'Id', 'c'),
        ('quotelines', 'LaborTypeId', 'labortypes', 'Id', 'n'),
        ('quotelines', 'PartId', 'parts', 'Id', 'n'),
        ('quotelines', 'QuoteId', 'quotes', 'Id', 'c'),
        ('quotes', 'AppointmentId', 'appointments', 'Id', 'c'),
        ('quotes', 'CreatedByMechanicId', 'people', 'Id', 'n'),
        ('quotes', 'VehicleId', 'vehicles', 'Id', 'c'),
        ('refreshtokens', 'MechanicId', 'people', 'Id', 'c'),
        ('vehicles', 'CustomerId', 'people', 'Id', 'c')
    ) AS e (tbl, col, ref_tbl, ref_col, rule)
    FULL JOIN (
        SELECT t.relname::text AS tbl,
               a.attname::text AS col,
               rt.relname::text AS ref_tbl,
               ra.attname::text AS ref_col,
               c.confdeltype::text AS rule
        FROM pg_constraint c
        JOIN pg_class t ON t.oid = c.conrelid
        JOIN pg_namespace n ON n.oid = t.relnamespace AND n.nspname = 'public'
        JOIN pg_class rt ON rt.oid = c.confrelid
        JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = c.conkey[1]
        JOIN pg_attribute ra ON ra.attrelid = c.confrelid AND ra.attnum = c.confkey[1]
        WHERE c.contype = 'f'
    ) a ON a.tbl = e.tbl AND a.col = e.col
    WHERE e.tbl IS NULL
       OR a.tbl IS NULL
       OR e.ref_tbl <> a.ref_tbl
       OR e.ref_col <> a.ref_col
       OR e.rule <> a.rule
) v;
